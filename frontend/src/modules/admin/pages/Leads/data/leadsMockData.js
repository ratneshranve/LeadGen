export const getStoredLeads = () => {
  try {
    const data = localStorage.getItem("leadflow_mock_leads");
    if (data) {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {}
  return initialLeadsData;
};

export const saveStoredLeads = (leads) => {
  try {
    localStorage.setItem("leadflow_mock_leads", JSON.stringify(leads));
  } catch (e) {}
};

export const getCustomSources = () => {
  try {
    const data = localStorage.getItem("leadflow_custom_sources");
    if (data) {
      return JSON.parse(data);
    }
  } catch (e) {}
  return ["Meta Ads", "Google Ads", "Website", "WhatsApp", "Referral", "Manual Entry"];
};

// Helper function to return ONLY Active lead sources (excluding inactive or deleted sources)
export const getActiveStoredSources = () => {
  try {
    const saved = localStorage.getItem("leadflow_mock_sources");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        const activeNames = parsed
          .filter((s) => s.status === "Active")
          .map((s) => s.name);
        if (activeNames.length > 0) {
          return activeNames;
        }
      }
    }
  } catch (e) {}

  return ["Meta Ads", "Google Ads", "Website", "WhatsApp", "Referral", "Manual Entry", "LinkedIn"];
};
